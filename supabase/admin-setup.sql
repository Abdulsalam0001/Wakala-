create or replace function public.is_active_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.admin_users au
    join public.admin_roles ar on ar.id = au.role_id
    where au.user_id = auth.uid()
      and au.status = 'active'
      and ar.name in ('super_admin', 'admin', 'moderator')
  );
$$;

create or replace function public.get_admin_role()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select ar.name
  from public.admin_users au
  join public.admin_roles ar on ar.id = au.role_id
  where au.user_id = auth.uid()
    and au.status = 'active'
  limit 1;
$$;

create or replace function public.is_super_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.admin_users au
    join public.admin_roles ar on ar.id = au.role_id
    where au.user_id = auth.uid()
      and au.status = 'active'
      and ar.name = 'super_admin'
  );
$$;

create table if not exists public.admin_roles (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text,
  permissions jsonb default '[]'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.admin_roles enable row level security;

create table if not exists public.admin_users (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references auth.users(id) on delete cascade,
  role_id bigint not null references public.admin_roles(id) on delete restrict,
  status text not null default 'active' check (status in ('active', 'inactive', 'suspended')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.admin_users enable row level security;

create or replace function public.update_admin_users_timestamp()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists update_admin_users_timestamp on public.admin_users;
create trigger update_admin_users_timestamp
before update on public.admin_users
for each row execute function public.update_admin_users_timestamp();

-- Seed default admin roles
insert into public.admin_roles (name, description, permissions) values
  ('super_admin', 'Full system access', '["all"]'::jsonb),
  ('admin', 'Standard admin access', '["users", "balances", "esim", "creators"]'::jsonb),
  ('moderator', 'Content moderation', '["creators", "review"]'::jsonb)
on conflict (name) do nothing;

-- Admin table policies
create policy "Admins can view admin users"
  on public.admin_users
  for select
  using (public.is_active_admin());

create policy "Only super admins can update admin status"
  on public.admin_users
  for update
  using (
    exists (
      select 1
      from public.admin_users au
      join public.admin_roles ar on ar.id = au.role_id
      where au.user_id = auth.uid()
        and au.status = 'active'
        and ar.name = 'super_admin'
    )
  );

