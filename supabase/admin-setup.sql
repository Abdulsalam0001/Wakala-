  on public.admin_roles
  for select
  using (public.is_active_admin());

-- ============================================================
-- Admin customer listing
-- ============================================================

drop function if exists public.admin_list_customers(text);

create function public.admin_list_customers(search_term text default '')
returns table (
  user_id uuid,
  full_name text,
  email text,
  phone text,
  account_number text,
  status text,
  created_at timestamptz
)
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  normalized_search text := trim(coalesce(search_term, ''));
begin
  if not public.is_active_admin() then
    raise exception 'Administrator access required';
  end if;

  return query
  select
    p.id,
    p.full_name,
    p.email,
    p.phone,
    w.account_number,
    coalesce(w.status, 'active'),
    p.created_at
  from public.profiles p
  left join lateral (
    select w1.account_number, w1.status
    from public.wallets w1
    where w1.user_id = p.id
    order by w1.created_at asc, w1.id asc
    limit 1
  ) w on true
  where normalized_search = ''
     or p.full_name ilike '%' || normalized_search || '%'
     or p.email ilike '%' || normalized_search || '%'
     or p.phone ilike '%' || normalized_search || '%'
     or w.account_number ilike '%' || normalized_search || '%'
  order by p.created_at desc;
end;
$$;

revoke execute on function public.admin_list_customers(text) from public;
grant execute on function public.admin_list_customers(text) to authenticated;

-- ============================================================
-- Admin customer balances
-- ============================================================

create or replace function public.admin_get_customer_balances(target_user_id uuid)
returns table (
  currency text,
  available numeric,
  pending numeric
)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.is_active_admin() then
    raise exception 'Administrator access required';
  end if;

  return query
  select wb.currency, wb.available, wb.pending
  from public.wallet_balances wb
  join public.wallets w on w.id = wb.wallet_id
  where w.user_id = target_user_id
  order by wb.currency;
end;
$$;

revoke execute on function public.admin_get_customer_balances(uuid) from public;
grant execute on function public.admin_get_customer_balances(uuid) to authenticated;

-- ============================================================
-- Admin wallet adjustment
-- ============================================================

create or replace function public.admin_adjust_wallet_balance(
  target_user_id uuid,
  target_currency text,
  adjustment_amount numeric,
  adjustment_direction text,
  adjustment_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  wallet_id_value bigint;
  currency_value text := upper(trim(target_currency));
  amount_value numeric := abs(adjustment_amount);
  direction_value text := lower(trim(adjustment_direction));
  new_balance numeric;
  reference_value text := 'ADM-' || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 20));
begin
  if not public.is_active_admin() then
    raise exception 'Administrator access required';
  end if;

  if amount_value <= 0 then
    raise exception 'Adjustment amount must be greater than zero';
  end if;

  if direction_value not in ('credit', 'debit') then
    raise exception 'Direction must be credit or debit';
  end if;

  select w.id
  into wallet_id_value
  from public.wallets w
  where w.user_id = target_user_id
  order by w.created_at asc, w.id asc
  limit 1
  for update;

  if wallet_id_value is null then
    raise exception 'Customer wallet not found';
  end if;

  insert into public.wallet_balances (wallet_id, currency)
  values (wallet_id_value, currency_value)
  on conflict (wallet_id, currency) do nothing;

  update public.wallet_balances
  set available = available + case when direction_value = 'credit' then amount_value else -amount_value end,
      updated_at = now()
  where wallet_id = wallet_id_value and currency = currency_value
  returning available into new_balance;

  insert into public.transactions (
    user_id, wallet_id, amount, currency, type, status, description, reference, metadata, completed_at
  ) values (
    target_user_id,
    wallet_id_value,
    case when direction_value = 'credit' then amount_value else -amount_value end,
    currency_value,
    'adjustment',
    'completed',
    coalesce(nullif(trim(adjustment_reason), ''), 'Administrative wallet adjustment'),
    reference_value,
    jsonb_build_object('source', 'admin', 'admin_user_id', auth.uid(), 'direction', direction_value, 'reason', adjustment_reason),
    now()
  );

  return jsonb_build_object(
    'success', true,
    'wallet_id', wallet_id_value,
    'currency', currency_value,
    'direction', direction_value,
    'adjustment_amount', amount_value,
    'new_available_balance', new_balance,
    'reference', reference_value
  );
end;
$$;

revoke execute on function public.admin_adjust_wallet_balance(uuid, text, numeric, text, text) from public;
grant execute on function public.admin_adjust_wallet_balance(uuid, text, numeric, text, text) to authenticated;

-- ============================================================
-- Admin dashboard overview
-- ============================================================

create or replace function public.admin_dashboard_overview()
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.is_active_admin() then
    raise exception 'Administrator access required';
  end if;

  return jsonb_build_object(
    'total_users', (select count(*) from public.profiles),
    'total_esim_orders', (select count(*) from public.esim_orders),
    'pending_esim_orders', (select count(*) from public.esim_orders where status in ('pending', 'pending_admin_review')),
    'balances', coalesce((
      select jsonb_agg(jsonb_build_object('currency', currency, 'balance', balance) order by currency)
      from (
        select wb.currency, sum(wb.available) as balance
        from public.wallet_balances wb
        group by wb.currency
      ) totals
    ), '[]'::jsonb),
    'recent_users', coalesce((
      select jsonb_agg(to_jsonb(recent) order by created_at desc)
      from (
        select p.full_name, p.phone, p.created_at
        from public.profiles p
        order by p.created_at desc
        limit 5
      ) recent
    ), '[]'::jsonb),
    'recent_esim_orders', coalesce((
      select jsonb_agg(to_jsonb(recent) order by created_at desc)
      from (
        select e.user_id, e.country_name, e.plan_data, e.status, e.created_at
        from public.esim_orders e
        order by e.created_at desc
        limit 5
      ) recent
    ), '[]'::jsonb),
    'recent_transactions', coalesce((
      select jsonb_agg(to_jsonb(recent) order by created_at desc)
      from (
        select t.type, t.amount, t.currency, t.status, t.created_at
        from public.transactions t
        order by t.created_at desc
        limit 10
      ) recent
    ), '[]'::jsonb)
  );
end;
$$;

revoke execute on function public.admin_dashboard_overview() from public;
grant execute on function public.admin_dashboard_overview() to authenticated;

