// Function to get banks by country code
function getBanksByCountry(countryCode) {
  return WAKALA_BANKS[countryCode]?.banks || [];
}

// Function to get country name by code
function getCountryName(countryCode) {
  return WAKALA_BANKS[countryCode]?.name || countryCode;
}

// Function to get all country codes
function getCountryCodes() {
  return Object.keys(WAKALA_BANKS);
}

// Function to get country info
function getCountryInfo(countryCode) {
  return WAKALA_BANKS[countryCode] || null;
}

// Function to get SWIFT code for a bank in a specific country
function getSwiftCode(countryCode, bankName) {
  const country = WAKALA_BANKS[countryCode];
  if (!country || !country.swift_codes) return null;
  return country.swift_codes[bankName] || null;
}

// Function to search banks across all countries
function searchBanks(query) {
  const results = [];
  const searchTerm = query.toLowerCase().trim();
  
  if (!searchTerm) return results;
  
  for (const [code, country] of Object.entries(WAKALA_BANKS)) {
    const matchedBanks = country.banks.filter(bank => 
      bank.toLowerCase().includes(searchTerm)
    );
    if (matchedBanks.length > 0) {
      results.push({
        countryCode: code,
        countryName: country.name,
        banks: matchedBanks
      });
    }
  }
  
  return results;
}

// Update the DOM function
function addBankDirectory() {
  const externalTab = document.getElementById('external-tab');
  const bankName = document.getElementById('bankName');

  if (!externalTab || !bankName) return;

  const countryGroup = document.createElement('div');
  countryGroup.className = 'form-group';

  countryGroup.innerHTML = `
    <label for="bankCountry">Recipient country</label>
    <select id="bankCountry" required>
      ${Object.entries(WAKALA_BANKS)
        .map(
          ([code, country]) =>
            `<option value="${code}">${country.name} (${country.currency})</option>`
        )
        .join('')}
    </select>
  `;

  const bankGroup = bankName.closest('.form-group');

  const bankSelect = document.createElement('select');
  bankSelect.id = 'bankName';
  bankSelect.name = bankName.name || 'bankName';
  bankSelect.className = bankName.className;
  bankSelect.required = true;

  bankGroup.replaceChild(bankSelect, bankName);

  externalTab.insertBefore(countryGroup, bankGroup);

  const countrySelect = document.getElementById('bankCountry');

  const updateBanks = () => {
    const country = WAKALA_BANKS[countrySelect.value];

    bankSelect.innerHTML =
      '<option value="">Choose a bank</option>' +
      country.banks
        .map(bank => `<option value="${bank}">${bank}</option>`)
        .join('');
  };

  countrySelect.addEventListener('change', updateBanks);

  updateBanks();
}

